/** Які області згадані серед слів (для розвʼязання тезок). */
export function detectOblastHints(words: string[]): Set<string> {
  const hints = new Set<string>();
  for (const w of words) {
    for (const [stem, oblast] of OBLAST_HINT_STEMS) {
      if (w.startsWith(stem)) {
        hints.add(oblast);
        break;
      }
    }
  }
  return hints;
}
